/** Translate a key, substituting {placeholders} when provided. */
export function tr(
  key: TranslationKey,
  lang: Language,
  vars?: Record<string, string | number>,
): string {
  let text: string = lang === 'am' ? am[key] || en[key] : en[key];
  if (vars) {
    for (const name of Object.keys(vars)) {
      text = text.split(`{${name}}`).join(String(vars[name]));
    }
  }
  return text;
}

export type TranslateFn = (
  key: TranslationKey,
  vars?: Record<string, string | number>,
) => string;
